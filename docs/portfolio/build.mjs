// Builds docs/UPWORK_PORTFOLIO.md from fields.json and prints each field's character count
// next to it, checked against Upwork's limits. Usage: node docs/portfolio/build.mjs
import { readFileSync, writeFileSync } from "node:fs";

const LIMITS = { title: 70, role: 100, description: 600 };
const f = JSON.parse(readFileSync("docs/portfolio/fields.json", "utf8"));
const len = (s) => [...s].length;
const check = (s, max) => `${len(s)} / ${max} characters ${len(s) <= max ? "(OK)" : "(TOO LONG)"}`;
const problems = [];
const note = (s, max, label) => {
  if (len(s) > max) problems.push(`${label} is ${len(s)} characters (max ${max})`);
  return check(s, max);
};
if (f.skills.length !== 5) problems.push(`skills: ${f.skills.length}, need exactly 5`);
if (/[—–]/.test(JSON.stringify(f))) problems.push("contains an em or en dash");

const repo = "https://github.com/youcallmejoaz/claude-ready-app-starter";
const md = `# Upwork portfolio entry

Generated by \`node docs/portfolio/build.mjs\` from \`docs/portfolio/fields.json\`. Character counts
are computed by that script.

## 1. Project title (pick one)

${f.titles.map((t, i) => `${i + 1}. ${t}  \n   _${note(t, LIMITS.title, `title ${i + 1}`)}_${i === f.recommendedTitle ? " **Recommended:** it leads with the two phrases clients search for, Claude Code and MCP." : ""}`).join("\n")}

## 2. Your role

${f.role}

_${note(f.role, LIMITS.role, "role")}_

## 3. Project description

${f.description}

_${note(f.description, LIMITS.description, "description")}_

The test count (98: 88 Vitest unit and integration tests plus 10 Playwright end to end tests)
comes from the real test run in this repository.

## 4. Skills (exactly 5)

${f.skills.map((s) => `- ${s}`).join("\n")}

_${f.skills.length} skills._ If Upwork does not offer one of these as a tag, swap only that one
(for example "Model Context Protocol (MCP)" for "AI Agent Development").

## 5. Content blocks, in this order

1. **Cover image:** \`docs/upwork-cover-a.png\` (1600 x 1200, 4:3). Alternative: \`docs/upwork-cover-b.png\`.
2. **Video:** upload \`clips/proposal_cut.mp4\` (61 seconds, voiced, no captions).
${f.screenshots.map((s, i) => `${i + 3}. **Screenshot:** \`${s.file}\`  \n   Caption: ${s.caption}`).join("\n")}
5. **Link:** ${repo}
6. **YouTube:** _add the link once the walkthrough is published._

## 6. Proposal snippet

${f.proposalSnippet}

_${len(f.proposalSnippet)} characters._
`;
writeFileSync("docs/UPWORK_PORTFOLIO.md", md);
console.log(`title: ${f.titles.map((t) => len(t)).join(", ")} | role: ${len(f.role)} | description: ${len(f.description)}`);
if (problems.length) {
  console.error("Problems:\n- " + problems.join("\n- "));
  process.exit(1);
}
